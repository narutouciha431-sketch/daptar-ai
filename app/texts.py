def money(n: int) -> str:
    return f"{n:,}".replace(",", " ") + " ₸"


def items_line(items: list[dict]) -> str:
    def q(x):
        return int(x) if float(x) == int(x) else x
    return ", ".join(f"{it['name']} ×{q(it['qty'])}" for it in items)


def date_kk_ru(iso: str) -> str:
    y, m, d = iso.split("-")
    return f"{d}.{m}.{y}"


