const RU = Object.fromEntries(Object.entries(KK).map(([r, k]) => [k, r]));
let uiLang = (() => { try { return localStorage.getItem('daptar-lang') || 'ru'; } catch { return 'ru'; } })();

function translateNode(root) {
  const dict = uiLang === 'kk' ? KK : RU;
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n; (n = walk.nextNode());) {
    const t = n.nodeValue.trim();
    if (t && dict[t] && !n.parentElement.closest('textarea,script,style,[translate=no]')) n.nodeValue = n.nodeValue.replace(t, dict[t]);
  }
}
function applyLang() {
  document.documentElement.lang = uiLang === 'kk' ? 'kk' : 'ru';
  translateNode(document.body);
  const b = document.getElementById('langBtn');
  if (b) b.textContent = uiLang === 'kk' ? 'Рус' : 'Қаз';
}
new MutationObserver(ms => { if (uiLang === 'kk') ms.forEach(m => m.addedNodes.forEach(n => n.nodeType === 1 ? translateNode(n) : null)); })
  .observe(document.documentElement, { childList: true, subtree: true });

document.addEventListener('DOMContentLoaded', () => {
  const slot = document.querySelector('[data-lang-slot]');
  if (slot) {
    const b = Object.assign(document.createElement('button'), { id: 'langBtn', type: 'button', className: 'ghost small lang-btn' });
    b.setAttribute('aria-label', 'Тіл / Язык');
    b.onclick = () => { uiLang = uiLang === 'kk' ? 'ru' : 'kk'; try { localStorage.setItem('daptar-lang', uiLang); } catch {} applyLang(); };
    slot.prepend(b);
  }
  applyLang();
});
